def test_uninstallation_paths() -> None:
    class dist:
        def iter_declared_entries(self) -> Iterator[str] | None:
            return iter(["file.py", "file.pyc", "file.so", "nopyc.py"])

        location = ""

    d = dist()

    paths = list(uninstallation_paths(d))

    expected = [
        "file.py",
        "file.pyc",
        "file.pyo",
        "file.so",
        "nopyc.py",
        "nopyc.pyc",
        "nopyc.pyo",
    ]

    assert paths == expected

    # Avoid an easy 'unique generator' bug
    paths2 = list(uninstallation_paths(d))

    assert paths2 == paths


def test_compressed_listing(tmpdir: Path) -> None:
    def in_tmpdir(paths: list[str]) -> list[str]:
        return [
            str(os.path.join(tmpdir, path.replace("/", os.path.sep))) for path in paths
        ]

    sample = in_tmpdir(
        [
            "lib/mypkg.dist-info/METADATA",
            "lib/mypkg.dist-info/PKG-INFO",
            "lib/mypkg/would_be_removed.txt",
            "lib/mypkg/would_be_skipped.skip.txt",
            "lib/mypkg/__init__.py",
            "lib/mypkg/my_awesome_code.py",
            "lib/mypkg/__pycache__/my_awesome_code-magic.pyc",
            "lib/mypkg/support/support_file.py",
            "lib/mypkg/support/more_support.py",
            "lib/mypkg/support/would_be_skipped.skip.py",
            "lib/mypkg/support/__pycache__/support_file-magic.pyc",
            "lib/random_other_place/file_without_a_dot_pyc",
            "bin/mybin",
        ]
    )

    # Create the required files
    for fname in sample:
        create_file(fname, "random blub")

    # Remove the files to be skipped from the paths
    sample = [path for path in sample if ".skip." not in path]

    expected_remove = in_tmpdir(
        [
            "bin/mybin",
            "lib/mypkg.dist-info/*",
            "lib/mypkg/*",
            "lib/random_other_place/file_without_a_dot_pyc",
        ]
    )

    expected_skip = in_tmpdir(
        [
            "lib/mypkg/would_be_skipped.skip.txt",
            "lib/mypkg/support/would_be_skipped.skip.py",
        ]
    )

    expected_rename = in_tmpdir(
        [
            "bin/",
            "lib/mypkg.dist-info/",
            "lib/mypkg/would_be_removed.txt",
            "lib/mypkg/__init__.py",
            "lib/mypkg/my_awesome_code.py",
            "lib/mypkg/__pycache__/",
            "lib/mypkg/support/support_file.py",
            "lib/mypkg/support/more_support.py",
            "lib/mypkg/support/__pycache__/",
            "lib/random_other_place/",
        ]
    )

    will_remove, will_skip = compress_for_output_listing(sample)
    will_rename = compress_for_rename(sample)
    assert sorted(expected_skip) == sorted(compact(will_skip))
    assert sorted(expected_remove) == sorted(compact(will_remove))
    assert sorted(expected_rename) == sorted(compact(will_rename))


def test_compact_keeps_minimal_parent_paths(tmpdir: Path) -> None:
    parent = os.path.join(tmpdir, "pkg")
    nested = os.path.join(parent, "module.py")
    deeper = os.path.join(parent, "subpkg", "module.py")
    sibling = os.path.join(tmpdir, "pkg-extra", "module.py")

    assert compact([nested, deeper, sibling, parent]) == {parent, sibling}


def test_compact_keeps_literal_trailing_star_paths(tmpdir: Path) -> None:
    # A trailing star is only special for display wildcards generated by pip.
    # A real POSIX filename ending with "*" must still be kept.
    plain = os.path.join(tmpdir, "pkg")
    star = os.path.join(tmpdir, "pkg*")

    assert compact([plain, star]) == {plain, star}


class TestUninstallPathSet:
    def test_blocked_first_move_preserves_original(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """Discard an unused stash without removing the original installation."""
        metadata = tmp_path / "sample-1.0.dist-info"
        metadata.mkdir()
        (metadata / "METADATA").write_text("Name: sample\nVersion: 1.0\n")
        dist = get_environment([str(tmp_path)]).get_distribution("sample")
        assert dist is not None

        path = tmp_path / "data.txt"
        path.write_text("original")

        pathset = UninstallPathSet(dist)
        monkeypatch.setattr(UninstallPathSet, "_permitted", mock_permitted)
        pathset.add(str(path))
        monkeypatch.setattr(os, "rename", Mock(side_effect=BlockedImportError("cold")))

        with pytest.raises(BlockedImportError):
            pathset.remove(auto_confirm=True)

        assert path.read_text() == "original"
        assert not pathset.can_rollback
        assert not pathset._moved_paths._save_dirs

    @pytest.mark.parametrize(
        "error", [OSError("cannot delete"), BlockedImportError("cold")]
    )
    def test_failed_first_move_retains_backup(
        self,
        tmp_path: Path,
        monkeypatch: pytest.MonkeyPatch,
        caplog: pytest.LogCaptureFixture,
        error: Exception,
    ) -> None:
        caplog.set_level("ERROR")

        metadata = tmp_path / "sample-1.0.dist-info"
        metadata.mkdir()
        (metadata / "METADATA").write_text("Name: sample\nVersion: 1.0\n")
        dist = get_environment([str(tmp_path)]).get_distribution("sample")
        assert dist is not None

        source = tmp_path / "package"
        source.mkdir()
        pathset = UninstallPathSet(dist)
        monkeypatch.setattr(UninstallPathSet, "_permitted", mock_permitted)
        for name in ("first", "second"):
            path = source / f"{name}.txt"
            path.write_text(name)
            pathset.add(str(path))

        def incomplete_removal(path: str) -> None:
            (Path(path) / "first.txt").unlink()
            raise error

        with monkeypatch.context() as patch:
            patch.setattr(os, "rename", Mock(side_effect=OSError("cross-device")))
            patch.setattr(shutil, "rmtree", incomplete_removal)
            with pytest.raises(type(error)):
                pathset.remove(auto_confirm=True)

        ((original, saved),) = pathset._moved_paths.recovery_paths
        backup = Path(saved)
        assert Path(original) == source
        assert not pathset.can_rollback
        assert not (source / "first.txt").exists()
        assert (source / "second.txt").read_text() == "second"

        assert repr(original) in caplog.text
        assert repr(saved) in caplog.text
        assert len(caplog.records) == 1

        (source / "first.txt").write_text("manually restored")
        pathset.rollback()
        pathset.commit()

        assert (source / "first.txt").read_text() == "manually restored"
        assert (backup / "first.txt").read_text() == "first"
        assert (backup / "second.txt").read_text() == "second"

    def test_manual_file_recovery_does_not_skip_pth_restoration(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        metadata = tmp_path / "sample-1.0.dist-info"
        metadata.mkdir()
        (metadata / "METADATA").write_text("Name: sample\nVersion: 1.0\n")
        dist = get_environment([str(tmp_path)]).get_distribution("sample")
        assert dist is not None

        source = tmp_path / "file.txt"
        source.write_text("original")
        pth = tmp_path / "example.pth"
        pth.write_bytes(b"keep\nremove\n")

        pathset = UninstallPathSet(dist)
        monkeypatch.setattr(UninstallPathSet, "_permitted", mock_permitted)
        pathset.add(str(source))
        pathset.add_pth(str(pth), "remove")

        pathset.remove(auto_confirm=True)
        assert pth.read_bytes() == b"keep\n"

        with monkeypatch.context() as patch:
            patch.setattr(os, "rename", Mock(side_effect=BlockedImportError("cold")))
            with pytest.raises(BlockedImportError):
                pathset.rollback()

        ((original, backup),) = pathset._moved_paths.recovery_paths
        assert pth.read_bytes() == b"keep\n"

        pathset.rollback()
        pathset.commit()

        assert pth.read_bytes() == b"keep\nremove\n"
        assert not Path(original).exists()
        assert Path(backup).read_text() == "original"

